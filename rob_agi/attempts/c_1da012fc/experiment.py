from rob_agi.colored_grid import ColoredGrid
from rob_agi.attempts.c_1da012fc.main import solve_1da012fc, extract_color_key, get_sorted_regions

def print_regions_and_colors(input_grid):
    color_key = extract_color_key(input_grid.values)
    sorted_regions = get_sorted_regions(input_grid.values)
    
    print("Color Key:", color_key)
    print("Number of regions:", len(sorted_regions))
    
    for i, region in enumerate(sorted_regions):
        new_color = color_key[i % len(color_key)]
        print(f"Region {i + 1}:")
        print(f"  Size: {len(region)}")
        print(f"  Top-left coordinate: {min(region)}")
        print(f"  Original color: {input_grid.values[region[0][0]][region[0][1]]}")
        print(f"  Assigned color: {new_color}")
        print(f"  Coordinates: {region[:5]}{'...' if len(region) > 5 else ''}")
        print()

